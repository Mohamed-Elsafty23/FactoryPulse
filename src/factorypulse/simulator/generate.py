"""Expand AI4I into timestamped sensor readings with physics-based failures."""

from __future__ import annotations

import json
import math
from datetime import datetime
from pathlib import Path

import click
from pyspark.sql import DataFrame, SparkSession, Window
from pyspark.sql import functions as F

from factorypulse.config import settings
from factorypulse.simulator.roster import OSF_THRESHOLD, ROSTER, WEAR_RATE
from factorypulse.spark import get_spark

PROFILE_PATH = Path(__file__).parent / "ai4i_profile.json"

SEED_AIR, SEED_TEMPD, SEED_RPM, SEED_TORQ = 101, 102, 103, 104
SEED_TWF, SEED_RNF, SEED_REPAIR = 105, 106, 107


def _load_profile() -> dict:
    """Load parameters generated by ``scripts/profile_ai4i.py``."""
    if not PROFILE_PATH.exists():
        raise FileNotFoundError(
            f"Missing {PROFILE_PATH}. Run `.venv/bin/python scripts/profile_ai4i.py` first."
        )
    return json.loads(PROFILE_PATH.read_text())


def _roster_df(spark: SparkSession) -> DataFrame:
    """Create a broadcastable machine-index lookup."""
    rows = [
        (
            index,
            machine.machine_id,
            machine.plant_id,
            machine.line_id,
            machine.machine_type,
            float(WEAR_RATE[machine.machine_type]),
            float(OSF_THRESHOLD[machine.machine_type]),
        )
        for index, machine in enumerate(ROSTER)
    ]
    return spark.createDataFrame(
        rows,
        "machine_index INT, machine_id STRING, plant_id STRING, line_id STRING, "
        "machine_type STRING, wear_rate DOUBLE, osf_threshold DOUBLE",
    )


def generate_telemetry(
    spark: SparkSession,
    n_rows: int,
    start: datetime,
    seed_offset: int = 0,
) -> DataFrame:
    """Build telemetry as a pure Spark transformation with no driver-side row loop."""
    if n_rows <= 0:
        raise ValueError("n_rows must be positive")

    profile = _load_profile()
    n_machines = len(ROSTER)
    seed = seed_offset
    # Pass the wall-clock value as text. Sending a naive Python datetime directly
    # makes PySpark interpret it in the host timezone before applying Spark's
    # session timezone, which can move a midnight start into the previous date.
    start_literal = start.isoformat(sep=" ")

    df = spark.range(0, n_rows).withColumnRenamed("id", "row_idx")
    df = (
        df.withColumn("machine_index", (F.col("row_idx") % n_machines).cast("int"))
        .withColumn("minute_index", (F.col("row_idx") / n_machines).cast("long"))
        .withColumn(
            "event_time",
            (F.lit(start_literal).cast("timestamp").cast("long") + F.col("minute_index") * 60).cast(
                "timestamp"
            ),
        )
    )

    df = df.join(F.broadcast(_roster_df(spark)), on="machine_index", how="inner")

    df = df.withColumn("cycle_length", (F.lit(220.0) / F.col("wear_rate")).cast("long")).withColumn(
        "tool_wear_min",
        ((F.col("minute_index") % F.col("cycle_length")) * F.col("wear_rate")).cast("int"),
    )

    air = profile["air_temp_k"]
    temperature_difference = profile["temp_diff_k"]
    rpm_profile = profile["rotational_speed_rpm"]
    torque_profile = profile["torque_nm"]
    correlation = profile["rpm_torque_corr"]

    df = df.withColumn(
        "air_temp_k",
        F.round(F.lit(air["mean"]) + F.randn(SEED_AIR + seed) * F.lit(air["std"]), 1),
    ).withColumn(
        "process_temp_k",
        F.round(
            F.col("air_temp_k")
            + F.lit(temperature_difference["mean"])
            + F.randn(SEED_TEMPD + seed) * F.lit(temperature_difference["std"]),
            1,
        ),
    )

    df = df.withColumn("z_rpm", F.randn(SEED_RPM + seed)).withColumn(
        "rotational_speed_rpm",
        F.round(F.lit(rpm_profile["mean"]) + F.col("z_rpm") * F.lit(rpm_profile["std"])).cast(
            "int"
        ),
    )
    df = df.withColumn(
        "torque_nm",
        F.round(
            F.lit(torque_profile["mean"])
            + F.lit(torque_profile["std"])
            * (
                F.lit(correlation) * F.col("z_rpm")
                + F.lit(math.sqrt(1 - correlation**2)) * F.randn(SEED_TORQ + seed)
            ),
            1,
        ),
    ).withColumn("torque_nm", F.greatest(F.col("torque_nm"), F.lit(1.0)))

    df = df.withColumn(
        "temp_diff_k", F.round(F.col("process_temp_k") - F.col("air_temp_k"), 2)
    ).withColumn(
        "power_w",
        F.round(
            F.col("torque_nm") * F.col("rotational_speed_rpm") * F.lit(2 * math.pi / 60.0),
            1,
        ),
    )

    hdf = (F.col("temp_diff_k") < 8.6) & (F.col("rotational_speed_rpm") < 1380)
    pwf = (F.col("power_w") < 3500) | (F.col("power_w") > 9000)
    osf = (F.col("tool_wear_min") * F.col("torque_nm")) > F.col("osf_threshold")
    twf = (F.col("tool_wear_min").between(200, 240)) & (F.rand(SEED_TWF + seed) < 0.05)
    rnf = F.rand(SEED_RNF + seed) < 0.001

    df = (
        df.withColumn("twf", twf)
        .withColumn("hdf", hdf)
        .withColumn("pwf", pwf)
        .withColumn("osf", osf)
        .withColumn("rnf", rnf)
        .withColumn(
            "failure_type",
            F.when(F.col("pwf"), "PWF")
            .when(F.col("osf"), "OSF")
            .when(F.col("hdf"), "HDF")
            .when(F.col("twf"), "TWF")
            .when(F.col("rnf"), "RNF")
            .otherwise("NONE"),
        )
        .withColumn("is_failure", F.col("failure_type") != F.lit("NONE"))
    )

    base_repair_minutes = (
        F.when(F.col("failure_type") == "PWF", 20)
        .when(F.col("failure_type") == "TWF", 35)
        .when(F.col("failure_type") == "HDF", 55)
        .when(F.col("failure_type") == "OSF", 120)
        .when(F.col("failure_type") == "RNF", 15)
        .otherwise(0)
    )
    df = df.withColumn(
        "repair_minutes",
        F.when(
            F.col("is_failure"),
            F.greatest(
                F.lit(5),
                F.round(
                    base_repair_minutes * (F.lit(0.6) + F.rand(SEED_REPAIR + seed) * F.lit(0.8))
                ).cast("int"),
            ),
        ).otherwise(F.lit(None).cast("int")),
    )

    machine_history = (
        Window.partitionBy("machine_id")
        .orderBy("event_time")
        .rowsBetween(Window.unboundedPreceding, Window.currentRow)
    )
    df = (
        df.withColumn(
            "last_fail_time",
            F.last(F.when(F.col("is_failure"), F.col("event_time")), ignorenulls=True).over(
                machine_history
            ),
        )
        .withColumn(
            "last_repair_minutes",
            F.last(F.when(F.col("is_failure"), F.col("repair_minutes")), ignorenulls=True).over(
                machine_history
            ),
        )
        .withColumn(
            "machine_status",
            F.when(
                F.col("last_fail_time").isNotNull()
                & (
                    F.col("event_time").cast("long")
                    < F.col("last_fail_time").cast("long") + F.col("last_repair_minutes") * 60
                ),
                F.lit("DOWN"),
            ).otherwise(F.lit("RUNNING")),
        )
    )

    df = (
        df.withColumn(
            "rotational_speed_rpm",
            F.when(F.col("machine_status") == "DOWN", 0).otherwise(F.col("rotational_speed_rpm")),
        )
        .withColumn(
            "torque_nm",
            F.when(F.col("machine_status") == "DOWN", 0.0).otherwise(F.col("torque_nm")),
        )
        .withColumn(
            "power_w",
            F.when(F.col("machine_status") == "DOWN", 0.0).otherwise(F.col("power_w")),
        )
    )

    df = (
        df.withColumn(
            "event_id",
            F.concat_ws(
                "-", F.col("machine_id"), F.date_format(F.col("event_time"), "yyyyMMddHHmm")
            ),
        )
        .withColumn("event_date", F.to_date("event_time"))
        .withColumn(
            "shift_name",
            F.when(F.hour("event_time").between(6, 13), "early")
            .when(F.hour("event_time").between(14, 21), "late")
            .otherwise("night"),
        )
        .withColumn("source_system", F.lit("telemetry_simulator"))
    )

    return df.select(
        "event_id",
        "machine_id",
        "plant_id",
        "line_id",
        "machine_type",
        "event_time",
        "event_date",
        "shift_name",
        "air_temp_k",
        "process_temp_k",
        "temp_diff_k",
        "rotational_speed_rpm",
        "torque_nm",
        "power_w",
        "tool_wear_min",
        "failure_type",
        "is_failure",
        "machine_status",
        "repair_minutes",
        "source_system",
    )


@click.command()
@click.option("--rows", default=None, type=click.IntRange(min=1), help="Total rows to generate.")
@click.option("--start", default="2025-10-01", help="First event date (YYYY-MM-DD).")
@click.option(
    "--defect-rate",
    default=None,
    type=click.FloatRange(min=0.0, max=0.5),
    help="Fraction of rows to corrupt.",
)
@click.option("--output", default=None, help="Override the output path.")
def main(rows: int | None, start: str, defect_rate: float | None, output: str | None) -> None:
    """Generate telemetry and write it to the landing zone as Parquet."""
    from factorypulse.simulator.defects import inject_defects

    n_rows = rows or settings.sim_rows
    rate = settings.sim_defect_rate if defect_rate is None else defect_rate
    output_path = output or settings.landing_path("telemetry")

    spark = get_spark("telemetry-simulator", shuffle_partitions=16)
    try:
        start_datetime = datetime.fromisoformat(start)
        telemetry = inject_defects(generate_telemetry(spark, n_rows, start_datetime), rate)

        # Object stores do not always remove partitions that are absent from a
        # replacement run. Delete this exact dataset path first so an earlier
        # run with a wider date range cannot leak stale rows into the result.
        hadoop_path = spark._jvm.org.apache.hadoop.fs.Path(output_path)
        filesystem = hadoop_path.getFileSystem(spark._jsc.hadoopConfiguration())
        filesystem.delete(hadoop_path, True)
        telemetry.write.mode("overwrite").partitionBy("event_date").parquet(output_path)

        written = spark.read.parquet(output_path)
        total = written.count()
        print(f"\n  rows requested : {n_rows:,}")
        print(f"  rows written   : {total:,}  (extra rows are injected duplicates)")
        print(f"  defect rate    : {rate}")
        print(f"  output         : {output_path}")
        print("\n  failure mix:")
        (
            written.groupBy("failure_type")
            .count()
            .withColumn("pct", F.round(F.col("count") / F.lit(total) * 100, 3))
            .orderBy(F.desc("count"))
            .show()
        )
    finally:
        spark.stop()


if __name__ == "__main__":
    main()
